-- Buyfirst Supabase schema
-- Run once in Supabase Dashboard > SQL Editor.
-- All browser access is constrained by RLS. Never use a secret/service-role key in the website.

create extension if not exists pgcrypto;

create type public.user_role as enum ('customer', 'admin');
create type public.order_state as enum ('pending', 'processing', 'shipped', 'out_for_delivery', 'delivered', 'cancelled');
create type public.payment_state as enum ('pending', 'paid', 'rejected');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  role public.user_role not null default 'customer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.products (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  category text not null default 'General',
  image_url text,
  images jsonb not null default '[]'::jsonb,
  cost_price numeric(12,2) not null default 0 check (cost_price >= 0),
  selling_price numeric(12,2) not null check (selling_price > 0),
  mrp numeric(12,2) not null check (mrp >= selling_price),
  stock integer not null default 0 check (stock >= 0),
  dispatch_days integer not null default 3 check (dispatch_days >= 0),
  tags text[] not null default '{}',
  variants text[] not null default '{}',
  is_digital boolean not null default false,
  digital_file_path text,
  is_active boolean not null default true,
  sku text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  user_id uuid not null references auth.users(id) on delete restrict,
  customer_name text not null,
  phone text not null,
  address text not null default '',
  city text not null default '',
  state text not null default '',
  pincode text not null default '',
  payment_method text not null check (payment_method in ('UPI', 'Card')),
  payment_reference text,
  payment_status public.payment_state not null default 'pending',
  status public.order_state not null default 'pending',
  subtotal numeric(12,2) not null check (subtotal >= 0),
  shipping_fee numeric(12,2) not null default 0 check (shipping_fee >= 0),
  total numeric(12,2) not null check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_title text not null,
  variant text not null default '',
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  created_at timestamptz not null default now()
);

create table public.enquiries (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  name text not null,
  email text not null,
  phone text,
  message text not null,
  created_at timestamptz not null default now()
);

create index orders_user_created_idx on public.orders(user_id, created_at desc);
create index order_items_order_idx on public.order_items(order_id);
create index products_active_created_idx on public.products(is_active, created_at desc);
create index enquiries_created_idx on public.enquiries(created_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_updated_at before update on public.profiles
for each row execute function public.set_updated_at();
create trigger products_updated_at before update on public.products
for each row execute function public.set_updated_at();
create trigger orders_updated_at before update on public.orders
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    nullif(new.raw_user_meta_data ->> 'phone', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

-- Secure order creation: price, shipping, and stock are calculated by Postgres,
-- not trusted from the browser. Payment remains pending until manually verified.
create sequence if not exists public.order_number_seq start 1001;

create or replace function public.create_customer_order(
  p_customer_name text,
  p_phone text,
  p_address text,
  p_city text,
  p_state text,
  p_pincode text,
  p_payment_method text,
  p_utr text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_order_id uuid := gen_random_uuid();
  v_order_number text;
  v_subtotal numeric(12,2) := 0;
  v_shipping numeric(12,2) := 0;
  v_total numeric(12,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_variant text;
  v_has_physical boolean := false;
begin
  if v_uid is null then raise exception 'Please sign in before placing an order'; end if;
  if length(trim(coalesce(p_customer_name, ''))) < 2 then raise exception 'Enter your name'; end if;
  if p_phone !~ '^[0-9]{10}$' then raise exception 'Enter a valid 10-digit phone number'; end if;
  if p_payment_method not in ('UPI', 'Card') then raise exception 'Unsupported payment method'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your cart is empty';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item ->> 'quantity')::integer;
    if v_qty < 1 or v_qty > 20 then raise exception 'Invalid item quantity'; end if;
    select * into v_product
      from public.products
      where id = (v_item ->> 'product_id')::bigint and is_active = true
      for update;
    if not found then raise exception 'A product is unavailable'; end if;
    if not v_product.is_digital and v_product.stock < v_qty then
      raise exception 'Insufficient stock for %', v_product.title;
    end if;
    if not v_product.is_digital then v_has_physical := true; end if;
    v_subtotal := v_subtotal + (v_product.selling_price * v_qty);
  end loop;

  if v_has_physical and v_subtotal < 499 then v_shipping := 49; end if;
  v_total := v_subtotal + v_shipping;
  v_order_number := 'BF' || nextval('public.order_number_seq')::text;

  insert into public.orders (
    id, order_number, user_id, customer_name, phone, address, city, state, pincode,
    payment_method, payment_reference, payment_status, status, subtotal, shipping_fee, total
  ) values (
    v_order_id, v_order_number, v_uid, trim(p_customer_name), p_phone,
    coalesce(p_address, ''), coalesce(p_city, ''), coalesce(p_state, ''), coalesce(p_pincode, ''),
    p_payment_method, nullif(trim(coalesce(p_utr, '')), ''), 'pending', 'pending',
    v_subtotal, v_shipping, v_total
  );

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item ->> 'quantity')::integer;
    v_variant := coalesce(v_item ->> 'variant', '');
    select * into v_product
      from public.products
      where id = (v_item ->> 'product_id')::bigint and is_active = true
      for update;

    insert into public.order_items (
      order_id, product_id, product_title, variant, quantity, unit_price
    ) values (
      v_order_id, v_product.id, v_product.title, v_variant, v_qty, v_product.selling_price
    );

    if not v_product.is_digital then
      update public.products set stock = stock - v_qty where id = v_product.id;
    end if;
  end loop;

  return jsonb_build_object('id', v_order_id, 'order_number', v_order_number,
    'subtotal', v_subtotal, 'shipping_fee', v_shipping, 'total', v_total,
    'payment_status', 'pending');
end;
$$;


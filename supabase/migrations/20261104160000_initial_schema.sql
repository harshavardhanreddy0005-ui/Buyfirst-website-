-- Remove broad defaults, then grant only required table actions.
revoke all on public.profiles, public.products, public.orders, public.order_items, public.enquiries from anon, authenticated;
grant select on public.products to anon, authenticated;
grant select, update on public.profiles to authenticated;
grant select on public.orders, public.order_items to authenticated;
grant insert on public.enquiries to anon, authenticated;
grant select, update, delete on public.enquiries to authenticated;
grant select, insert, update, delete on public.products to authenticated;
grant update on public.orders to authenticated;
grant usage, select on sequence public.order_number_seq to authenticated;
revoke execute on function public.create_customer_order(text,text,text,text,text,text,text,text,jsonb) from public, anon;
grant execute on function public.create_customer_order(text,text,text,text,text,text,text,text,jsonb) to authenticated;
grant execute on function public.is_admin() to anon, authenticated;

create policy "Public can view active products"
on public.products for select to anon, authenticated
using (is_active = true or public.is_admin());

create policy "Admins manage products"
on public.products for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Users view own profile"
on public.profiles for select to authenticated
using (id = (select auth.uid()) or public.is_admin());

create policy "Users update own customer profile"
on public.profiles for update to authenticated
using (id = (select auth.uid()) and role = 'customer')
with check (id = (select auth.uid()) and role = 'customer');

create policy "Admins manage profiles"
on public.profiles for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Customers view own orders"
on public.orders for select to authenticated
using (user_id = (select auth.uid()) or public.is_admin());

create policy "Admins update orders"
on public.orders for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Customers view own order items"
on public.order_items for select to authenticated
using (
  exists (
    select 1 from public.orders o
    where o.id = order_id and (o.user_id = (select auth.uid()) or public.is_admin())
  )
);

create policy "Public submit enquiries"
on public.enquiries for insert to anon, authenticated
with check (
  length(trim(name)) between 2 and 120
  and length(trim(email)) between 5 and 254
  and length(trim(message)) between 2 and 5000
  and (user_id is null or user_id = (select auth.uid()))
);

create policy "Admins read enquiries"
on public.enquiries for select to authenticated
using (public.is_admin());

create policy "Admins update enquiries"
on public.enquiries for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "Admins delete enquiries"
on public.enquiries for delete to authenticated
using (public.is_admin());

